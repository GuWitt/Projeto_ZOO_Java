    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
      String descricao = txtDescricao.getText().trim();
        if(descricao.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Digite a descrição do servico");
            return;
        }
      int idAnimal;
      int idZelador;
            
      try{ idAnimal = Integer.parseInt(txtIDA.getText().trim());
        idZelador = Integer.parseInt(txtIDZ.getText().trim());
       
        if (idAnimal <= 0 || idZelador <= 0) {
        JOptionPane.showMessageDialog(this, "Os ids devem ser positivos");
        return;}
         
      }catch (NumberFormatException erro){
        JOptionPane.showMessageDialog(this, "Informe IDs numericos validos");
        return;
      }

      String sql = "INSERT INTO servico_zoo (animal_id, zelador_id, descricao) VALUES (?, ?, ?)";

     try (Connection conex = Conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sql)){
            
            stmt.setInt(1, idAnimal);
            stmt.setInt(2, idZelador);
            stmt.setString(3, descricao);

            int linhas = stmt.executeUpdate();

            if(linhas == 1){
            JOptionPane.showMessageDialog(this, "Serviço cadastrado com sucesso!");
            }
     }catch (SQLException erro){
            JOptionPane.showMessageDialog(this, "Erro ao cadastrar serviço " + erro.getMessage());
     }
     limparCampos();
     atualizarTabela();
    }//GEN-LAST:event_btnSalvarActionPerformed

