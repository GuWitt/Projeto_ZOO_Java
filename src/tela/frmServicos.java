    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        int linha = tblServicos.getSelectedRow();
        
        if (linha == -1){
            JOptionPane.showMessageDialog(this, "Selecione um serviço na tabela para alterar");
            return;
        }
        
        //2. Pegar id da linha selecionada
        // ID NÃO SERÁ ALTERADO
        int id = Integer.parseInt(tblServicos.getValueAt(linha, 0).toString());
        
        //3. Ler os novos valores digitados nos campos especie, nome, idade
        String data = txtDataServico.getText().trim();
        int ida = Integer.parseInt(txtIDA.getText().trim());
        int idz = Integer.parseInt(txtIDZ.getText().trim());
        String descricao = txtDescricao.getText().trim();
        
        //4. Validar se os campos estão preenchidos
        if (data.isEmpty() || ida <= 0 || idz <= 0 || descricao.isEmpty()){
            JOptionPane.showMessageDialog(this, "Nenhuma dos campos pode ser vazio ou incorreto! Preencha todos os campos corretamente!");
            return;
        }
       
        
        //6. Pedir confirmação antes de gravar no Banco de Dados
        int resposta = JOptionPane.showConfirmDialog(this, "Deseja realmente alterar esses dados do serviço de id: " + id + " no sistema?",
                                                    "Confirmar Alteração", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE );
        
        if (resposta != JOptionPane.YES_OPTION){
            return;
        }    
        
        //7. Alteramos apenas a especie, nome e idade
        // O WHERE
        String sql = "UPDATE servico_zoo "
                   + "SET animal_id = ?, zelador_id = ?, descricao = ? "
                   + "WHERE id = ?";
        
        try (Connection conex = Conexao.conectar();
             PreparedStatement stmt = conex.prepareStatement(sql)){
            //8. Preencher os Parametros(?) na mesma ordem do SQL
            
            stmt.setInt(1,ida);
            stmt.setInt(2,idz);
            stmt.setString(3,descricao);
            stmt.setInt(4, id);
            
            //9. Executamos a alteração no Banco de Dados
            int registros = stmt.executeUpdate();
            if (registros > 0) {
                JOptionPane.showMessageDialog(this, "Serviço alterado com sucesso!");
                atualizarTabela();
                limparCampos();
                
            } else {
                JOptionPane.showMessageDialog(this, "Serviço não encontrado");
            }
        } catch(SQLException erro) {
            JOptionPane.showMessageDialog(this, "Erro ao alterar serviço: " + erro.getMessage());
        }
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tblServicos.getSelectedRow();
        
        if (linha == -1){
            JOptionPane.showMessageDialog(this, "Selecione um serviço para excluir!");
            return;
        }
        
        int id = Integer.parseInt(tblServicos.getValueAt(linha, 0).toString());
        
        int resposta = JOptionPane.showConfirmDialog(this,
                                                    "Deseja realmente excluir o serviço do id " + id + " do sistema?",
                                                    "Confirmar exclusão",
                                                    JOptionPane.YES_NO_OPTION,
                                                    JOptionPane.QUESTION_MESSAGE);
        
        if (resposta != JOptionPane.YES_OPTION){
            return;
        }    
        
        String sql = "DELETE FROM servico_zoo "
                   + "WHERE id = ? ";
        
        try (Connection conex = Conexao.conectar();
             PreparedStatement stmt = conex.prepareStatement(sql)) {
             
            stmt.setInt(1, id);
            
            int registros = stmt.executeUpdate();
            if (registros > 0) {
                JOptionPane.showMessageDialog(this,"Serviço excluido com sucesso!");
                atualizarTabela();
            } else {
                JOptionPane.showMessageDialog(this,"Algo deu errado! Tente novamente mais tarde.");
            }
            
        } catch(SQLException erro){
                JOptionPane.showMessageDialog(this, "Erro ao excluir Serviço: " + erro.getMessage());
        };
    }//GEN-LAST:event_btnExcluirActionPerformed

