    private void btnBuscarAnimalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarAnimalActionPerformed
       txtNomeAnimal.setText("");
       int idAnimal;
       
       try{ 
            idAnimal = Integer.parseInt(txtIDA.getText().trim());
            if(idAnimal <= 0){
                JOptionPane.showMessageDialog(this, "O id do animal deve ser POSITIVO!");
                return;
            }
       } catch (NumberFormatException erro){
           JOptionPane.showMessageDialog(this, "Digite um ID de animal VALIDO!");
           return;
       }
       
       String sql = "SELECT nome FROM animal "
               +    "WHERE id = ?";
       
       try (Connection conex = Conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sql)){
           
           stmt.setInt(1, idAnimal);
           
           try (ResultSet rs = stmt.executeQuery()){
               if (rs.next()) {
                   txtNomeAnimal.setText(rs.getString("nome"));
               } else {
                   JOptionPane.showMessageDialog(this,"Animal não encontrado");
               }
           }
       } catch(SQLException erro){
           JOptionPane.showMessageDialog(this,"Erro ao buscar Animal " + erro.getMessage());
       }
           
           
    }//GEN-LAST:event_btnBuscarAnimalActionPerformed

