    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        //1. Capturar a linha selecionada
        int linha = tbAnimal.getSelectedRow();
        
        if (linha == -1){
            JOptionPane.showMessageDialog(this, "Selecione um animal na tabela para alterar");
            return;
        }
        
        //2. Pegar id da linha selecionada
        // ID NÃO SERÁ ALTERADO
        int id = Integer.parseInt(tbAnimal.getValueAt(linha, 0).toString());
        
        //3. Ler os novos valores digitados nos campos especie, nome, idade
        String especie = txtEspecie.getText().trim();
        String nome = txtNome.getText().trim();
        String idadeTXT = txtIdade.getText().trim();
        
        //4. Validar se os campos estão preenchidos
        if (especie.isEmpty() || nome.isEmpty() || idadeTXT.isEmpty()){
            JOptionPane.showMessageDialog(this, "Nenhuma dos campos pode ser vazio! Preencha todos os campos!");
            return;
        }
        
        //5. Verificar se o Idade é um número inteiro válido
        int idade;
        
        try {
            idade = Integer.parseInt(idadeTXT);
            
            if (idade < 0) {
                JOptionPane.showMessageDialog(this, "A idade não pode ser Negativa! Insira um número válido.");
                return;
            }
        }catch(NumberFormatException erro){
            JOptionPane.showMessageDialog(this, "A idade deve ser um número Inteiro");
            return;
        }
        
        //6. Pedir confirmação antes de gravar no Banco de Dados
        int resposta = JOptionPane.showConfirmDialog(this, "Deseja realmente alterar esses dados do animal de id: " + id + " no sistema?",
                                                    "Confirmar Alteração", JOptionPane.YES_NO_CANCEL_OPTION, JOptionPane.QUESTION_MESSAGE );
        
        if (resposta != JOptionPane.YES_OPTION){
            return;
        }    
        
        //7. Alteramos apenas a especie, nome e idade
        // O WHERE
        String sql = "UPDATE animal "
                   + "SET especie = ?, nome = ?, idade = ? "
                   + "WHERE id = ?";
        
        try (Connection conex = Conexao.conectar();
             PreparedStatement stmt = conex.prepareStatement(sql)){
            //8. Preencher os Parametros(?) na mesma ordem do SQL
            stmt.setString(1,especie);
            stmt.setString(2,nome);
            stmt.setInt(3,idade);
            stmt.setInt(4,id);
            
            //9. Executamos a alteração no Banco de Dados
            int registros = stmt.executeUpdate();
            if (registros > 0) {
                JOptionPane.showMessageDialog(this, "Animal alterado com sucesso!");
                atualizarTabela();
                txtID.setText("");
                txtEspecie.setText("");
                txtNome.setText("");
                
            } else {
                JOptionPane.showMessageDialog(this, "Animal não encontrado");
            }
        } catch(SQLException erro) {
            JOptionPane.showMessageDialog(this, "Erro ao alterar animal: " + erro.getMessage());
        }
        
        
    }//GEN-LAST:event_btnAlterarActionPerformed

