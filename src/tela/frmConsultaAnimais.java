    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tbAnimal.getSelectedRow();
        
        if (linha == -1){
            JOptionPane.showMessageDialog(this, "Selecione um animal para excluir!");
            return;
        }
        
        int id = Integer.parseInt(tbAnimal.getValueAt(linha, 0).toString());
        
        int resposta = JOptionPane.showConfirmDialog(this,
                                                    "Deseja realmente excluir o animal do id " + id + " do sistema?",
                                                    "Confirmar exclusão",
                                                    JOptionPane.YES_NO_CANCEL_OPTION,
                                                    JOptionPane.QUESTION_MESSAGE);
        
        if (resposta != JOptionPane.YES_OPTION){
            return;
        }    
        
        String sql = "DELETE FROM animal "
                   + "WHERE id = ? ";
        
        try (Connection conex = Conexao.conectar();
             PreparedStatement stmt = conex.prepareStatement(sql)) {
             
            stmt.setInt(1, id);
            
            int registros = stmt.executeUpdate();
            if (registros > 0) {
                JOptionPane.showMessageDialog(this,"Animal excluido com sucesso!");
                atualizarTabela();
            } else {
                JOptionPane.showMessageDialog(this,"Algo deu errado! Tente novamente mais tarde.");
            }
            
        } catch(SQLException erro){
                JOptionPane.showMessageDialog(this, "Erro ao excluir Animal: " + erro.getMessage());
        };
    }//GEN-LAST:event_btnExcluirActionPerformed

