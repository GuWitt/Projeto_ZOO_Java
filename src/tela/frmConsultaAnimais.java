    private void btnLocalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLocalizarActionPerformed
        String pesquisa = txtPesquisar.getText().trim();
        
        
        if (pesquisa.isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                                        "Digite o nome ou parte do nome do animal.", 
                                        "Pesquisa Vazia", 
                                        JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        DefaultTableModel modelo = (DefaultTableModel) tbAnimal.getModel();
        
        modelo.setRowCount(0);
        
        
        String modoPesq = cmbPesquisarPor.getSelectedItem().toString();
        String sql = "";
        if (modoPesq == "Nome"){
            sql = "SELECT * FROM animal "
                   + "WHERE nome ILIKE ? "
                   + "ORDER BY nome"; 
        } else {
            sql = "SELECT * FROM animal "
                   + "WHERE especie ILIKE ? "
                   + "ORDER BY nome"; 
        }
        
        
        try (Connection conex = Conexao.conectar();
             PreparedStatement stmt = conex.prepareStatement(sql)) {
            
            stmt.setString(1,"%" + pesquisa + "%");
            
            try (ResultSet resultado = stmt.executeQuery()){
                while (resultado.next()){
                    modelo.addRow(new Object [] {
                        resultado.getInt("id"),
                        resultado.getString("especie"),
                        resultado.getString("nome"),
                        resultado.getInt("idade")
                    });
                }
            }
            
            if (modelo.getRowCount() == 0){
             JOptionPane.showMessageDialog(this,
                                            "Nenhum animal encontrado para: " + pesquisa,
                                            "Resultado da Pesquisa", JOptionPane.INFORMATION_MESSAGE);
            }
            
        } catch(SQLException erro){
            JOptionPane.showMessageDialog(this, 
                                            "Erro ao localizar animal:\n" + erro.getMessage(),
                                            "Erro no Banco de Dados", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnLocalizarActionPerformed

